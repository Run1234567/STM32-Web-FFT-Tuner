// ==============================================================================
// 函数声明
// 注意：duty_cycle 参数范围变更为 0 ~ 10000 (代表 0.00% ~ 100.00%)
// ==============================================================================
void RUN_pwm_init(RUN_PWM_enum pwm_ch, uint32_t freq, uint16_t duty_cycle);
